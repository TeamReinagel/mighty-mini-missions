"""Convert the K-2 monthly milestones spreadsheet into netlify/lib/milestones.mjs.

Usage (from mighty-mini-missions/):
    python3 netlify/tools/import_milestones.py "/path/to/Kindergarten-Second Grade Monthly Milestones.xlsx"

Each sheet is a grade. Row 1 holds subject areas; column A holds months (September-August).
Rows after August (sources, pacing notes) are ignored.
"""

import json
import sys
from pathlib import Path

import openpyxl

MONTHS = ["September", "October", "November", "December", "January", "February",
          "March", "April", "May", "June", "July", "August"]

OUT = Path(__file__).resolve().parent.parent / "lib" / "milestones.mjs"


def clean(value):
    return " ".join(str(value).split()) if value is not None else ""


def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    grades = {}
    for ws in wb.worksheets:
        rows = [r for r in ws.iter_rows(values_only=True) if any(c is not None for c in r)]
        areas = [clean(a).rstrip(":") for a in rows[0][1:] if a]
        months = {}
        for row in rows[1:]:
            month = clean(row[0])
            if month not in MONTHS:
                continue
            # Cells can hold several goals on separate lines; keep them as a list.
            months[month] = {
                area: [clean(line) for line in str(cell).splitlines() if clean(line)]
                for area, cell in zip(areas, row[1:]) if cell
            }
        grades[ws.title] = {"areas": areas, "months": months}

    body = json.dumps(grades, indent=2, ensure_ascii=False)
    OUT.write_text(
        "// Generated by netlify/tools/import_milestones.py from the K-2 monthly milestones spreadsheet.\n"
        "// Re-run the script after editing the spreadsheet instead of editing this file.\n"
        f"export const MILESTONES = {body};\n"
    )
    print(f"Wrote {OUT} ({', '.join(f'{g}: {len(d['months'])} months' for g, d in grades.items())})")


if __name__ == "__main__":
    main(sys.argv[1])
